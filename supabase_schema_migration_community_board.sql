-- ── 조회수 — NOTICE와 동일하게 클라이언트 UPDATE 정책 없이 RPC로만 증가 ──

CREATE OR REPLACE FUNCTION public.increment_community_post_view_count(p_post_id bigint)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  UPDATE public."COMMUNITY_POST" SET "VIEW_COUNT" = "VIEW_COUNT" + 1 WHERE "POST_ID" = p_post_id;
$$;
REVOKE ALL ON FUNCTION public.increment_community_post_view_count(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.increment_community_post_view_count(bigint) TO authenticated, anon;

