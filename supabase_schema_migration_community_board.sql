-- 이제 COMMUNITY_COMMENT가 존재하므로 ACCEPTED_COMMENT_ID FK를 건다.
-- ADD CONSTRAINT는 IF NOT EXISTS를 지원하지 않아(Postgres 제약), 먼저 지우고
-- 다시 걸어야 이 파일 전체를 처음부터 다시 실행해도 안전하다(파일의 다른
-- 모든 문장은 CREATE ... IF NOT EXISTS/DROP ... IF EXISTS로 이미 재실행 가능함).
ALTER TABLE public."COMMUNITY_POST" DROP CONSTRAINT IF EXISTS "community_post_accepted_comment_fk";
ALTER TABLE public."COMMUNITY_POST"
  ADD CONSTRAINT "community_post_accepted_comment_fk"
  FOREIGN KEY ("ACCEPTED_COMMENT_ID") REFERENCES public."COMMUNITY_COMMENT"("COMMENT_ID") ON DELETE SET NULL;

-- 채택 답변 검증: QnA 글에서만, 그 글에 달린 "최상위 답변"만(대댓글 채택 불가)
-- 채택할 수 있다. COMMUNITY_POST UPDATE RLS가 이미 글쓴이 본인만 통과시키므로
-- "질문자만 채택 가능"은 RLS가 보장하고, 이 트리거는 값 자체의 유효성만 본다
-- (notice_pin_limit_reached와 같은 BEFORE UPDATE 검증 트리거 패턴).
CREATE OR REPLACE FUNCTION public.enforce_community_accept_answer() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW."ACCEPTED_COMMENT_ID" IS NOT NULL AND NEW."ACCEPTED_COMMENT_ID" IS DISTINCT FROM OLD."ACCEPTED_COMMENT_ID" THEN
    IF NEW."CATEGORY" <> 'QNA' THEN
      RAISE EXCEPTION 'community_accept_not_qna' USING ERRCODE = 'P0001';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM public."COMMUNITY_COMMENT" c
      WHERE c."COMMENT_ID" = NEW."ACCEPTED_COMMENT_ID"
        AND c."POST_ID" = NEW."POST_ID"
        AND c."PARENT_COMMENT_ID" IS NULL
    ) THEN
      RAISE EXCEPTION 'community_accept_invalid_answer' USING ERRCODE = 'P0001';
    END IF;
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_community_accept_answer ON public."COMMUNITY_POST";
CREATE TRIGGER trg_community_accept_answer BEFORE UPDATE ON public."COMMUNITY_POST"
  FOR EACH ROW EXECUTE FUNCTION public.enforce_community_accept_answer();

