-- 6개 카테고리(오늘 온 전리품/자유/QnA/정보/나만의 청음실/팁)를 한 테이블로
-- 묶고 CATEGORY로 구분한다 — 카테고리마다 별 테이블을 두면 목록/검색/신고가
-- 전부 N배로 늘어나고, 다섯 카테고리는 실제로 "제목+사진+본문"으로 완전히
-- 동일한 입력이라 분리할 이유가 없다. 카테고리별 전용 필드(오늘 온 전리품의
-- 앨범 다중 첨부, 정보 게시판의 위치, QnA의 채택 답변)만 컬럼/조인 테이블로
-- 추가한다. 댓글도 "답변"과 한 테이블(COMMUNITY_COMMENT)을 공유한다 — QnA는
-- UI에서만 "답변"으로 부르고 채택 여부(COMMUNITY_POST.ACCEPTED_COMMENT_ID)만
-- 얹는다, 데이터 모양 자체는 자유게시판 댓글과 동일(PARENT_COMMENT_ID 1단계
-- 스레딩 — SPIN_LOG_COMMENT/VINYL_COMMENT와 같은 패턴).
--
-- 커뮤니티 게시글은 항상 전체 공개다(비공개 옵션 없음) — community-albums와
-- 같은 이유: 게시판은 애초에 공유가 목적이라 프로필 공개 여부와 무관하게
-- 노출되어야 한다.

CREATE TABLE IF NOT EXISTS public."COMMUNITY_POST" (
    "POST_ID"            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CATEGORY"           text NOT NULL,
    "TITLE"              text NOT NULL CHECK (char_length("TITLE") BETWEEN 1 AND 100),
    "CONTENT"            text NOT NULL CHECK (char_length("CONTENT") BETWEEN 1 AND 5000),
    -- [{ "url": "https://...", "type": "image" }, ...] — NOTICE.MEDIA_ITEMS와 동일 모양
    -- (영상은 v1 범위 밖이라 type은 항상 "image"지만, 추후 확장 여지를 위해
    -- 별도 컬럼 대신 NOTICE와 같은 구조를 그대로 재사용한다).
    "MEDIA_ITEMS"        jsonb NOT NULL DEFAULT '[]'::jsonb,
    "AUTHOR_ID"          uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    "VIEW_COUNT"         integer NOT NULL DEFAULT 0,
    -- QnA 전용: 질문 작성자가 채택한 답변(최상위 답변만, 대댓글은 채택 불가).
    -- FK는 COMMUNITY_COMMENT 생성 후 아래에서 ALTER TABLE로 추가(순환 참조).
    "ACCEPTED_COMMENT_ID" bigint,
    -- 정보 게시판 전용 위치 공유(구글맵 Places 선택 결과).
    "PLACE_NAME"         text,
    "PLACE_ADDRESS"      text,
    "LATITUDE"           double precision,
    "LONGITUDE"          double precision,
    "CREATED_AT"         timestamp with time zone DEFAULT now(),
    "UPDATED_AT"         timestamp with time zone DEFAULT now(),
    CONSTRAINT "community_post_category_check" CHECK ("CATEGORY" IN ('ARRIVAL', 'FREE', 'QNA', 'INFO', 'LISTENING_ROOM', 'TIP')),
    CONSTRAINT "community_post_media_items_is_array" CHECK (jsonb_typeof("MEDIA_ITEMS") = 'array'),
    CONSTRAINT "community_post_media_items_max_5" CHECK (jsonb_array_length("MEDIA_ITEMS") <= 5),
    -- 위치 필드는 정보 게시판에서만 채워진다 — 다른 카테고리에서 실수로/악의적으로
    -- 채워 넣는 것을 DB 레벨에서 막는다.
    CONSTRAINT "community_post_location_only_info" CHECK (
      "CATEGORY" = 'INFO' OR (
        "PLACE_NAME" IS NULL AND "PLACE_ADDRESS" IS NULL AND "LATITUDE" IS NULL AND "LONGITUDE" IS NULL
      )
    )
);

CREATE INDEX IF NOT EXISTS "idx_community_post_category_created"
  ON public."COMMUNITY_POST" ("CATEGORY", "CREATED_AT" DESC);
CREATE INDEX IF NOT EXISTS "idx_community_post_author"
  ON public."COMMUNITY_POST" ("AUTHOR_ID");

